def main() -> int:
    cfg = load_config()
    (tables_dir,) = ensure_dirs(cfg["paths"]["tables_dir"])
    result = clean_dataset()

    # Configuration membership, derived rather than typed.
    membership: dict[str, list[str]] = {}
    for name, config in FEATURE_CONFIGS.items():
        for feature in config.features:
            membership.setdefault(feature, []).append(name)

    missing = result.clean.isna().sum()
    n_rows = len(result.clean)

    rows = []
    for spec in VARIABLES:
        name = spec.name
        category = CATEGORY.get(name, "uncertain_provenance")
        if spec.uncertain and category == "legitimate_pre_index":
            category = "uncertain_provenance"
        in_configs = sorted(membership.get(name, []))
        valid_configs = [c for c in in_configs
                         if FEATURE_CONFIGS[c].valid_for_clinical_interpretation]
        rows.append({
            "variable": name,
            "human_readable": spec.description.split(",")[0].split(".")[0][:80],
            "dtype": "interval-encoded ordinal"
            if name in result.bin_map and len(result.bin_map[name]) > 2
            else "binary/categorical",
            "n_missing": int(missing.get(name, 0)),
            "missing_fraction": round(float(missing.get(name, 0)) / n_rows, 4),
            "n_levels": len(result.bin_map.get(name, [])),
            "measurement_time": "index assessment"
            if category in ("legitimate_pre_index", "incorporation_risk",
                            "consequence_of_advanced_disease")
            else "post-diagnosis",
            "available_at_index": AVAILABILITY.get(name, "available"),
            "constructs_or_stages_outcome": CONSTRUCTS_OUTCOME.get(name, "no"),
            "leakage_category": category,
            "cost_tier": spec.tier,
            "decision": "excluded from all valid configurations"
            if not valid_configs else "included",
            "config_membership": ";".join(in_configs) if in_configs else "none",
            "n_valid_configs": len(valid_configs),
            "uncertainty_flag": bool(spec.uncertain),
            "uncertainty_note": (spec.uncertainty_note or "")[:300],
            "evidence": EVIDENCE.get(name, spec.rationale[:200]),
        })

    registry = pd.DataFrame(rows)
    registry_path = project_root() / "data" / "feature_registry.csv"
    registry.to_csv(registry_path, index=False)
    print(f"wrote {registry_path} ({len(registry)} variables)")

    registry.to_csv(tables_dir / "table_47_feature_registry.csv", index=False)
    summary = (
        registry.groupby("leakage_category")
        .agg(n_variables=("variable", "size"),
             n_excluded=("n_valid_configs", lambda s: int((s == 0).sum())),
             variables=("variable", lambda s: ", ".join(sorted(s))))
        .reset_index()
        .sort_values("n_variables", ascending=False)
    )
    summary.to_csv(tables_dir / "table_47_registry_summary.csv", index=False)
    print("wrote table_47_feature_registry.csv and table_47_registry_summary.csv")
    print()
    print(summary[["leakage_category", "n_variables", "n_excluded"]]
          .to_string(index=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
