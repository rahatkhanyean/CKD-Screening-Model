"""Stage 22: build the machine-readable feature-availability and leakage registry.

The registry is the single declarative source describing, for every column,
what it is, when it becomes knowable, whether it participates in constructing
the outcome, and therefore whether it may enter a model. Feature
configurations are derived from it (``ckd.features.registry``) rather than
maintained separately, so a classification cannot drift out of step with the
configuration that depends on it.

Leakage categories follow the taxonomy the manuscript uses:

``direct_outcome_copy``
    A renamed copy of the target.
``deterministic_outcome_derivative``
    A deterministic or near-deterministic function of the target or of the
    quantity defining it.
``post_diagnosis``
    Recorded only after the diagnosis exists; unavailable at index time.
``diagnostic_criterion_input``
    A legitimate contemporaneous measurement that is nevertheless an input to
    a KDIGO criterion for CKD itself, so using it risks incorporation bias.
    KDIGO 2024 defines CKD by GFR <60 mL/min/1.73 m2 *or* a marker of kidney
    damage, of which albuminuria (ACR >=30 mg/g) is the first listed. Serum
    creatinine is the input to the eGFR equation and therefore to the GFR
    limb; urine albumin is the albuminuria limb.
``possible_criterion_sediment``
    A urine sediment finding. KDIGO lists "urine sediment abnormalities" and
    "persistent haematuria" among the damage markers, so urinary red cells
    are criterion-adjacent; pyuria and bacteriuria point to infection rather
    than to CKD, and the release does not say which reading is intended.
    Separated from ``diagnostic_criterion_input`` because the incorporation
    risk is real but weaker and partly unverifiable.
``correlated_renal_biomarker``
    Tracks renal function and correlates with the outcome, but is **not** a
    KDIGO criterion for CKD. Blood urea is the clearest case: it appears
    nowhere in the KDIGO definition, and it is confounded by protein intake,
    catabolic state, hydration and gastrointestinal bleeding. Using such a
    variable is not incorporation bias; it is ordinary correlated
    information, and conflating the two overstates the leakage claim.
``consequence_of_advanced_disease``
    A downstream physiological consequence of established disease. Valid to
    measure, but its discriminative value comes from severity rather than
    from early detectability.
``legitimate_pre_index``
    Available before the diagnostic work-up and not part of the criterion.
``uncertain_provenance``
    Meaning, timing or coding could not be established from the release.

Output
------
data/feature_registry.csv                    the registry (source of truth)
reports/tables/table_47_feature_registry.csv publication copy
reports/tables/table_47_registry_summary.csv counts per category

Usage
-----
    python scripts/22_build_feature_registry.py
"""

