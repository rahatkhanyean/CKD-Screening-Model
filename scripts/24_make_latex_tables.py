        r"last two columns show.}",
        r"\label{tab:casemixsim}",
        r"\centering",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{p{2.6cm}p{3.3cm}cccc}",
        r"\toprule",
